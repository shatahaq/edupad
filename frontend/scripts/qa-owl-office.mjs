import { resolve, dirname } from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'
import assert from 'node:assert/strict'
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..')
const {chromium}=await import(pathToFileURL(resolve(root,'.venv/Lib/site-packages/playwright/driver/package/index.mjs')).href)
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true})
try{
  const page=await browser.newPage({viewport:{width:1600,height:1000}})
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto('http://127.0.0.1:5173/office?preview=1')
  await page.waitForFunction(()=>performance.getEntriesByType('resource').some(e=>e.name.includes('/frontend/src/game/events.ts')))
  const eventsUrl=await page.evaluate(()=>performance.getEntriesByType('resource').find(e=>e.name.includes('/frontend/src/game/events.ts'))?.name)
  await page.waitForFunction(async url=>(await import(url)).officeGameEvents.currentFurnitureLayout().length>0,eventsUrl)
  await page.waitForTimeout(1200)
  await page.screenshot({path:resolve(root,'.test-tmp/office-modular-overview.png')})
  const getLayout=()=>page.evaluate(async url=>(await import(url)).officeGameEvents.currentFurnitureLayout(),eventsUrl)
  const clickWorld=async (x,y)=>{
    const rect=await page.locator('canvas').boundingBox()
    await page.mouse.click(rect.x+x/1448*rect.width,rect.y+y/1086*rect.height)
  }
  const canvas=await page.locator('canvas').boundingBox()
  const editorToggle=await page.getByRole('button',{name:'Atur furnitur',exact:true}).boundingBox()
  const camera=await page.locator('.office-camera-controls').boundingBox()
  assert.ok(editorToggle.x>=canvas.x+canvas.width-1,'Furniture control stays outside the office')
  assert.ok(camera.x>=canvas.x+canvas.width-1,'Zoom control stays outside the office')
  assert.equal(await page.locator('.office-agent-tab').count(),7,'All seven owl tabs are shown below the office')
  assert.equal(await page.locator('.office-world-stage').evaluate(element=>getComputedStyle(element).boxShadow),'none','Office has no outer frame shadow')
  const dock=await page.locator('.office-agent-dock').boundingBox()
  assert.ok(dock.y>=canvas.y+canvas.height-1,'Owl tabs stay below the office canvas')
  assert.equal(await page.getByText('Mode pratinjau').count(),0)
  assert.equal(await page.getByText('Geser untuk menjelajah').count(),0)
  await clickWorld(726,330)
  await page.getByRole('dialog',{name:'Detail PIXEL'}).waitFor()
  assert.ok((await page.locator('.office-story-paragraph').innerText()).length>180)
  assert.equal(await page.evaluate(()=>document.elementFromPoint(800,25)?.classList.contains('office-detail-backdrop')),true,'Topbar is covered by the modal blur')
  await page.waitForTimeout(300)
  await page.screenshot({path:resolve(root,'.test-tmp/office-owl-story.png')})
  await page.getByRole('button',{name:'Tutup detail'}).click()
  await clickWorld(1070,350)
  await page.getByRole('dialog',{name:'Detail Tutor Room'}).waitFor()
  assert.ok((await page.locator('.office-story-paragraph').innerText()).length>180)
  await page.waitForTimeout(300)
  await page.screenshot({path:resolve(root,'.test-tmp/office-room-story.png')})
  await page.getByRole('button',{name:'Tutup detail'}).click()
  // Real UI interactions: furniture dialog, blocking backdrop, editor and persistence.
  await clickWorld(726,238)
  await page.getByRole('dialog',{name:'Detail Meja riset'}).waitFor()
  assert.equal(await page.locator('.office-furniture-portrait').getAttribute('src'),'/assets/office/furniture-muted/1.png')
  await page.screenshot({path:resolve(root,'.test-tmp/office-furniture-detail.png')})
  await page.getByText('OBJEK TERPILIH',{exact:true}).click()
  assert.equal(await page.getByRole('dialog',{name:'Detail Meja riset'}).count(),1)
  await page.getByRole('button',{name:'Atur posisi furnitur →'}).click()
  await page.getByRole('button',{name:'Selesai mengatur furnitur'}).waitFor()
  const editingCanvas=await page.locator('canvas').boundingBox()
  const workshop=await page.locator('.owl-workshop').boundingBox()
  assert.ok(workshop.x>=editingCanvas.x+editingCanvas.width-1,'Expanded catalog stays outside the office')
  await page.screenshot({path:resolve(root,'.test-tmp/office-editor-expanded.png')})
  await page.getByRole('button',{name:'Tambah Tanaman',exact:true}).click()
  assert.equal(await page.locator('.owl-workshop-catalog').count(),0)
  const before=(await getLayout()).length
  await clickWorld(500,250)
  assert.equal((await getLayout()).length,before+1,'Plant added by snapping to nearby floor')
  assert.match(await page.getByRole('status').innerText(),/terdekat/)
  const plant=(await getLayout()).at(-1)
  assert.ok(plant)
  assert.notEqual(plant.x,496,'Furniture is not placed inside the wall')
  const rect=await page.locator('canvas').boundingBox()
  const world=(x,y)=>({x:rect.x+x/1448*rect.width,y:rect.y+y/1086*rect.height})
  await page.mouse.move(world(plant.x,plant.y).x,world(plant.x,plant.y).y)
  await page.mouse.down();await page.mouse.move(world(1104,552).x,world(1104,552).y,{steps:12});await page.mouse.up()
  assert.equal((await getLayout()).find(item=>item.id===plant.id).x,1104,'Drag saved')
  await page.screenshot({path:resolve(root,'.test-tmp/office-furniture-editor.png')})
  await page.reload()
  await page.waitForFunction(async ({url,id})=>(await import(url)).officeGameEvents.currentFurnitureLayout().some(item=>item.id===id),{url:eventsUrl,id:plant.id})
  await page.waitForTimeout(1200)
  const savedLayout=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('edupad-owl-furniture-v2')||'[]'))
  assert.equal((await savedLayout()).find(item=>item.id===plant.id).x,1104,'Layout survives reload')
  await page.getByRole('button',{name:'Atur furnitur',exact:true}).click()
  await clickWorld(1104,552)
  await page.getByRole('button',{name:'Hapus tanaman',exact:true}).click()
  assert.equal((await savedLayout()).length,before,'Deletion saved')
  await page.getByRole('button',{name:'Selesai',exact:true}).click()
  for(let i=0;i<8;i++){
    const button=page.getByRole('button',{name:'Perbesar kantor',exact:true})
    if(await button.isDisabled())break
    await button.click()
  }
  assert.equal(await page.getByRole('button',{name:'Perbesar kantor',exact:true}).isDisabled(),true)
  await page.getByRole('button',{name:'Tampilkan seluruh kantor',exact:true}).click()
  // Mock backend lifecycle through the same event bridge used by React; no API call.
  await page.evaluate(async url=>{
    const {officeGameEvents}=await import(url)
    officeGameEvents.updateAgents(officeGameEvents.currentAgents().map(a=>({...a,state:'failed',task:'Pengujian error lokal',updated_at:new Date().toISOString()})))
  },eventsUrl)
  await page.screenshot({path:resolve(root,'.test-tmp/office-owl-errors.png')})
  assert.deepEqual(errors,[],'No browser runtime errors')
  await page.setViewportSize({width:900,height:700})
  await page.waitForTimeout(300)
  await page.screenshot({path:resolve(root,'.test-tmp/office-narrow-layout.png')})
  console.log('PASS: seamless tiled floor, seven owl tabs, outside controls, bot/room stories, full-screen blur, furniture portrait, safe auto-placement, drag, reload persistence, delete, zoom limit, error events; no browser errors')
}finally{await browser.close()}
